/**
 * The stylesheets that the palette module generates: the `@mokly/ui` theme
 * and the palette part of the `mokly-html` Markdown style. Each renderer
 * takes a palette and returns CSS text, which the generator formats with
 * Prettier and writes or checks.
 */
import { DOCUMENT_ROLES, PREVIEW_ROLES, themeRoles } from "./palette-roles.mjs";
import { declarations, scheme } from "./palette-sources.mjs";

/** The repository path of the palette module that every stylesheet comes from. */
export const PALETTE_SOURCE = "packages/ui/src/palette/palette.ts";

/** The command that writes the generated stylesheets again. */
export const GENERATE_COMMAND = "npm run palette:generate";

/** The first comment of every generated stylesheet. */
const HEADER = `/* Generated from ${PALETTE_SOURCE} by
   packages/ui/scripts/palette-generate.mjs. Do not edit this file: change the
   palette module or the role table of the generator, then run
   ${GENERATE_COMMAND}. */`;

const THEME_INTRO = `/* The theme of every shell root and of the standalone stub's document: the
   Canvas roles as --cv-*, and the tokens of the shell, which take their values
   from them as docs/protocol/mokly-viewer-palette.md records. This block holds
   the Light half. Every themed role is redeclared for Dark below, so a role
   never exists in one appearance only. No rule declares the public accent
   overrides --mokly-accent, --mokly-accent-contrast and --mokly-accent-soft,
   so a host's value, also one that a root inherits, wins in both appearances.
   Each use reads its override with the private default of its root's
   appearance as the fallback. */`;

const PREVIEW_INTRO = `/* Preview tokens describe what a device screen shows, so they never follow the
   interface appearance: a light preview inside a dark catalogue keeps its
   light surface, ink and status indicators. */`;

const DARK_INTRO = `/* The Dark half. Auto follows the reader's system through CSS alone, so a
   dark reader never sees a light first paint and no script decides the
   appearance. An explicit choice wins over the system in either direction.
   Each rule selects a root that states its appearance, never a host page.
   The stub's document states no appearance until the bundle runs, so it
   takes Auto; a shell root without the mark stays Light. */`;

const STUB_RULES = `/* The stub page around the standalone shell: no margin, the full viewport
   without scrolling, and the shell's background and type, also before the
   bundle runs and without JavaScript. */
.mbk-document,
.mbk-document > body {
  margin: 0;
  min-height: 100%;
}

.mbk-document > body {
  height: 100vh;
  overflow: hidden;
  background: var(--chrome-bg);
  color: var(--chrome-ink);
  font-family: var(--sans);
  line-height: 1.5;
  -webkit-font-smoothing: antialiased;
}`;

const DOCUMENT_INTRO = `/* The colours and the fonts of the Markdown documents, from the palette that
   the shell draws in. The typography of document.css, which follows this part
   in the inlined stylesheet, reads them. A dark document states its colour
   scheme in the style of its root. */`;

/** The selectors of the theme's Light block and of its preview tokens. */
const ROOT = [".mbk", ".mbk-document"];

/** The roots that take Auto, under a dark system. */
const AUTO_DARK = [
  '.mbk[data-mokly-theme="auto"]',
  '.mbk-document[data-mokly-theme="auto"]',
  ".mbk-document:not([data-mokly-theme])",
];

/** The roots that state Dark. */
const EXPLICIT_DARK = [
  '.mbk[data-mokly-theme="dark"]',
  '.mbk-document[data-mokly-theme="dark"]',
];

/** One rule: each selector on its own line, then one declaration a line. */
function rule(selectors, pairs, indent = "") {
  const body = pairs.map(
    ([property, value]) => `${indent}  ${property}: ${value};`,
  );
  return [
    `${selectors.map((selector) => `${indent}${selector}`).join(",\n")} {`,
    ...body,
    `${indent}}`,
  ].join("\n");
}

/** The parts of a stylesheet, one blank line apart, with a final newline. */
function stylesheet(parts) {
  return `${[HEADER, ...parts].join("\n\n")}\n`;
}

/**
 * The `@mokly/ui` theme: the Light and Dark roles of the shell on the root
 * class and the stub's document class, the preview tokens, and the stub
 * page's own rules.
 */
export function themeStylesheet(palette) {
  const roles = themeRoles(palette);
  const light = declarations(roles, scheme(palette, "light"));
  const dark = declarations(roles, scheme(palette, "dark"));
  const preview = declarations(PREVIEW_ROLES, scheme(palette, "light"));
  const auto = rule(AUTO_DARK, dark, "  ");
  return stylesheet([
    `${THEME_INTRO}\n${rule(ROOT, light)}`,
    `${PREVIEW_INTRO}\n${rule(ROOT, preview)}`,
    `${DARK_INTRO}\n@media (prefers-color-scheme: dark) {\n${auto}\n}`,
    rule(EXPLICIT_DARK, dark),
    STUB_RULES,
  ]);
}

/**
 * The palette part of the `mokly-html` Markdown style: the custom properties
 * of the Light and Dark documents, which the hand-kept typography reads.
 */
export function documentPaletteStylesheet(palette) {
  const light = declarations(DOCUMENT_ROLES, scheme(palette, "light"));
  const dark = declarations(DOCUMENT_ROLES, scheme(palette, "dark"));
  return stylesheet([
    `${DOCUMENT_INTRO}\n${rule(["html"], light)}`,
    rule(['html[style*="dark"]'], dark),
  ]);
}

/** Every stylesheet that the palette generates, with its repository path. */
export function paletteStylesheets(palette) {
  return [
    { path: "packages/ui/src/theme/theme.css", css: themeStylesheet(palette) },
    {
      path: "crates/mokly-html/src/document_palette.css",
      css: documentPaletteStylesheet(palette),
    },
  ];
}
