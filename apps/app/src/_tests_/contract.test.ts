import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { test } from "node:test";

import { apiDataReasons } from "../api/error-data";
import { apiCodes } from "../api/errors";
import { apiReasons } from "../api/reasons";
import { cataloguedFailures } from "./failures";
import { repositoryRoot } from "./root";
import { icons } from "../components/icons";

function read(path: string): string {
  return readFileSync(resolve(repositoryRoot, path), "utf8");
}

function object(value: unknown): Record<string, unknown> {
  assert.ok(
    typeof value === "object" && value !== null && !Array.isArray(value),
  );
  return Object.fromEntries(Object.entries(value));
}

/** The variants of the error object: one for each data type, one for the rest. */
function errorVariants(): Record<string, unknown>[] {
  const document: unknown = JSON.parse(read("docs/api/openapi.json"));
  const components = object(object(document).components);
  const schemas = object(components.schemas);
  const error = object(object(object(schemas.Error).properties).error);
  assert.ok(Array.isArray(error.oneOf), "Error.error must list its variants");
  return error.oneOf.map(object);
}

function errorEnum(
  variant: Record<string, unknown>,
  field: "reason" | "code",
): string[] {
  const inventory = object(object(variant.properties)[field]).enum;
  assert.ok(
    Array.isArray(inventory),
    `Error.error.${field} must declare an enum`,
  );
  return inventory.map((value: unknown) => {
    assert.ok(typeof value === "string");
    return value;
  });
}

test("the client's reason union is the OpenAPI enum", () => {
  const documented = errorVariants().flatMap((variant) =>
    errorEnum(variant, "reason"),
  );
  assert.deepEqual([...apiReasons].sort(), documented.sort());
});

test("the client's code union is the OpenAPI enum", () => {
  for (const variant of errorVariants())
    assert.deepEqual([...apiCodes].sort(), errorEnum(variant, "code").sort());
});

test("the client parses data for exactly the reasons the OpenAPI pairs with it", () => {
  const carrying = errorVariants()
    .filter((variant) => "data" in object(variant.properties))
    .flatMap((variant) => errorEnum(variant, "reason"));
  assert.deepEqual([...apiDataReasons].sort(), carrying.sort());
});

test("every reason the client knows is answered in the protocol", () => {
  // The tests build a failure from a reason alone and take the code and the
  // status from this table, so the table has to answer for every reason and
  // answer with a code the envelope can carry.
  const catalogued = cataloguedFailures();
  for (const reason of apiReasons) {
    const answer = catalogued.get(reason);
    assert.ok(answer, `rest-api.md must answer for ${reason}`);
    assert.ok(
      (apiCodes as readonly string[]).includes(answer.code),
      `${reason} is answered with an uncatalogued code: ${answer.code}`,
    );
    assert.ok(
      answer.status >= 400 && answer.status < 600,
      `${reason} is answered with ${answer.status}`,
    );
  }
});

test("the product's icon vocabulary matches the catalogue's own map", () => {
  const source = read("docs/mockups/src/screens/product/icons.tsx");
  const map = /export const icons = \{\n([\s\S]*?)\n\} as const/.exec(source);
  assert.ok(map, "the catalogue must export one icon map");
  const catalogued = map[1]
    .split("\n")
    .map((line) =>
      /^\s*([A-Za-z]+):\s*([A-Za-z0-9]+),$/.exec(line.trim() ? line : ""),
    )
    .filter((match): match is RegExpExecArray => match !== null)
    .map((match) => `${match[1]}:${match[2]}`);
  const local = Object.entries(icons).map(
    ([name, glyph]) =>
      `${name}:${(glyph as { displayName?: string }).displayName ?? name}`,
  );
  assert.deepEqual(
    catalogued.map((entry) => entry.split(":")[0]).sort(),
    local.map((entry) => entry.split(":")[0]).sort(),
  );
});

test("the generated client is present and typed from the committed document", () => {
  const schema = read("apps/app/src/api/generated/schema.ts");
  assert.match(schema, /auto-generated by openapi-typescript/);
  assert.match(schema, /"\/v1\/session"/);
  assert.match(schema, /getSession/);
});
