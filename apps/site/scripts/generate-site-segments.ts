import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { SITE_OUTPUT_FIRST_SEGMENTS, SITE_PATHS } from "../src/navigation.js";

const siteRoot = path.resolve(import.meta.dirname, "..");
const defaultOutput = path.resolve(siteRoot, "../worker/src/site-segments.ts");
const defaultDist = path.resolve(siteRoot, "dist");
const ignoredBuildOutputs = new Set(["404.html", "_headers", "index.html"]);

/** Derive the sorted first segments owned by the production static site. */
export function siteFirstSegments(
  routes: readonly string[],
  outputs: readonly string[],
): string[] {
  const segments = new Set(outputs);
  for (const route of routes) {
    if (!route.startsWith("/")) {
      throw new Error(`site route must be absolute: ${route}`);
    }
    const segment = route.split("/")[1];
    if (segment) segments.add(segment);
  }
  for (const segment of segments) {
    if (
      !segment ||
      segment.includes("/") ||
      segment === "." ||
      segment === ".."
    ) {
      throw new Error(`invalid site first segment: ${segment}`);
    }
  }
  return [...segments].sort();
}

/** Render the committed Worker module from the canonical site declarations. */
export function renderSiteSegments(segments: readonly string[]): string {
  const values = segments
    .map((segment) => `  ${JSON.stringify(segment)},`)
    .join("\n");
  return `/**
 * Generated by \`apps/site/scripts/generate-site-segments.ts\` from the static
 * site's routes and output names. Run the site route generator instead of
 * editing this file directly.
 */
export const SITE_FIRST_SEGMENTS = [
${values}
] as const;
`;
}

async function builtFirstSegments(dist: string): Promise<string[] | undefined> {
  let entries;
  try {
    entries = await readdir(dist, { withFileTypes: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
  return entries
    .filter((entry) => !ignoredBuildOutputs.has(entry.name))
    .map((entry) => entry.name)
    .sort();
}

function difference(
  left: readonly string[],
  right: readonly string[],
): string[] {
  const accepted = new Set(right);
  return left.filter((value) => !accepted.has(value));
}

/** Generate or check the committed route module, including built-output drift. */
export async function generateSiteSegments(options: {
  check: boolean;
  dist?: string;
  output?: string;
}): Promise<void> {
  const segments = siteFirstSegments(
    Object.values(SITE_PATHS),
    SITE_OUTPUT_FIRST_SEGMENTS,
  );
  const built = await builtFirstSegments(options.dist ?? defaultDist);
  if (built !== undefined) {
    const unexpected = difference(built, segments);
    const missing = difference(segments, built);
    if (unexpected.length || missing.length) {
      throw new Error(
        `site output names drifted from the origin-router set` +
          ` (unexpected: ${unexpected.join(", ") || "none"};` +
          ` missing: ${missing.join(", ") || "none"})`,
      );
    }
  }

  const output = options.output ?? defaultOutput;
  const source = renderSiteSegments(segments);
  if (!options.check) {
    await writeFile(output, source);
    return;
  }
  let committed;
  try {
    committed = await readFile(output, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      throw new Error(`generated site segment module is missing: ${output}`, {
        cause: error,
      });
    }
    throw error;
  }
  if (committed !== source) {
    throw new Error(
      "generated site segment module is stale; run npm run site:routes",
    );
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateSiteSegments({ check: process.argv.includes("--check") });
}
