//! Pure dependency traversal for generated TypeScript modules.

use std::any::TypeId;
use std::collections::{BTreeMap, BTreeSet};

use ts_rs::{Config, TS, TypeVisitor};

/// One declaration per file, with imports and transitive type dependencies.
pub struct TypeModules {
    config: Config,
    visited: BTreeSet<TypeId>,
    files: BTreeMap<String, String>,
}

impl Default for TypeModules {
    fn default() -> Self {
        Self {
            config: Config::default().with_large_int("number"),
            visited: BTreeSet::new(),
            files: BTreeMap::new(),
        }
    }
}

impl TypeModules {
    /// Add a root type and every type its declaration references.
    pub fn add<T: TS + 'static>(&mut self) {
        self.visit::<T>();
    }

    /// Return file basenames and exact source bytes in a stable order.
    pub fn finish(self) -> BTreeMap<String, String> {
        self.files
    }
}

impl TypeVisitor for TypeModules {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() || !self.visited.insert(TypeId::of::<T>()) {
            return;
        }
        let name = T::ident(&self.config);
        let mut text = String::from("// Generated by cargo xtask generate-types. Do not edit.\n\n");
        let imports: BTreeSet<_> = T::dependencies(&self.config)
            .into_iter()
            .filter(|dependency| {
                dependency.type_id != TypeId::of::<T>() && dependency.ts_name != name
            })
            .map(|dependency| dependency.ts_name)
            .collect();
        for dependency in &imports {
            text.push_str(&format!(
                "import type {{ {dependency} }} from \"./{dependency}.js\";\n"
            ));
        }
        if !imports.is_empty() {
            text.push('\n');
        }
        text.push_str("// prettier-ignore\nexport ");
        text.push_str(&T::decl(&self.config));
        text.push('\n');
        let text = text
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
            + "\n";
        self.files.insert(format!("{name}.ts"), text);
        T::visit_dependencies(self);
    }
}

