//! Deterministic ts-rs declaration generation without file writes.

use std::collections::BTreeMap;

use ts_rs::{Config, TS};

use crate::catalogue::CatalogueModel;
use crate::deployment::DeploymentFileV1;
use crate::public_detail::{EntryDetailV3, LiveDescriptorV3};
use crate::public_index::CatalogueReadModel;
use crate::snapshot::{CatalogueChangeSnapshotV4, RemovedPagePreview};
use crate::type_modules::TypeModules;

use crate::prop_schema::{Constant, JsonType, Primitive, PropSchema, Types};
use crate::versions;

/// Generate the viewer's shared model module in a fixed declaration order.
/// Later catalogue, detail, live, and snapshot shapes each own a module.
pub fn generate() -> String {
    let config = Config::default().with_large_int("number");
    let mut text = String::from("// Generated by cargo xtask generate-types. Do not edit.\n\n");
    for declaration in [
        Primitive::decl(&config),
        JsonType::decl(&config),
        Types::decl(&config),
        Constant::decl(&config),
        PropSchema::decl(&config),
    ] {
        text.push_str("// prettier-ignore\nexport ");
        text.push_str(&declaration);
        text.push_str("\n\n");
    }
    for (name, version) in [
        ("CatalogueIndexVersion", versions::CATALOGUE_INDEX),
        ("DeploymentFileVersion", versions::DEPLOYMENT_FILE),
        ("EntryDetailVersion", versions::ENTRY_DETAIL),
        ("ChangeSnapshotVersion", versions::CHANGE_SNAPSHOT),
        ("LiveDescriptorVersion", versions::LIVE_DESCRIPTOR),
    ] {
        text.push_str(&format!("export type {name} = {version};\n"));
    }
    let lines: Vec<_> = text.lines().map(str::trim_end).collect();
    format!("{}\n", lines.join("\n"))
}

/// Generate transitive catalogue, public index, detail and live type modules.
pub fn catalogue_modules() -> BTreeMap<String, String> {
    let mut modules = TypeModules::default();
    modules.add::<CatalogueModel>();
    modules.add::<CatalogueReadModel>();
    modules.add::<DeploymentFileV1>();
    modules.add::<EntryDetailV3>();
    modules.add::<LiveDescriptorV3>();
    modules.add::<CatalogueChangeSnapshotV4>();
    modules.add::<RemovedPagePreview>();
    let mut files = modules.finish();
    files.insert("Namespace.ts".into(), crate::namespace::typescript());
    if let Some(capability) = files.get_mut("RenderCapability.ts") {
        let header = "// Generated by cargo xtask generate-types. Do not edit.\n\n";
        let import =
            "import type { VIEWER_DIRECTORY } from \"../../catalogue/delivery_paths.js\";\n\n";
        *capability = capability.replacen(header, &format!("{header}{import}"), 1);
    }
    files
}
