import path from "node:path";

import { minimatch } from "minimatch";

import { isSafeRepositoryPath } from "@mokly/viewer/data";

import { isResolvedEntryOrInventoriedSource } from "../config/entry_membership.js";
import { isInside, toPosixPath } from "../config/paths.js";
import type { ResolvedConfig } from "../config/types.js";
import { MoklyError, errorMessage } from "../errors.js";
import { MANIFEST_NAME } from "../registry/manifest.js";

import { walkFiles } from "./discovery.js";
import {
  assertSafeGeneratedPath,
  assertSafeGeneratedTree,
} from "./reserved_tree.js";
import { sourceDenialMessage } from "./source_denial.js";
