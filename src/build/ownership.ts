const ENCODED_HEADER = "<!-- Generated by mokly; ownership=v1; source-base64=";
const ENCODED_HEADER_PATTERN =
  /^<!-- Generated by mokly; ownership=v1; source-base64=([A-Za-z0-9+/]+={0,2})\. Do not edit\. -->(?:\r\n|\n)/;
const FORMER_ENCODED_HEADER_PATTERN =
  /^<!-- Generated by mokabook; ownership=v1; source-base64=([A-Za-z0-9+/]+={0,2})\. Do not edit\. -->(?:\r\n|\n)/;
const LEGACY_HEADER_PATTERN =
  /^<!-- Generated by mokly from ([^\r\n]+)\. Do not edit\. -->(?:\r\n|\n)/;
const FORMER_LEGACY_HEADER_PATTERN =
  /^<!-- Generated by mokabook from ([^\r\n]+)\. Do not edit\. -->(?:\r\n|\n)/;

/** Create the ownership header for a generated HTML document. */
export function generatedHeader(sourceRelativePath: string): string {
  const encodedSource = Buffer.from(sourceRelativePath, "utf8").toString(
    "base64",
  );
  return `${ENCODED_HEADER}${encodedSource}. Do not edit. -->\n`;
}

/** Read the source path from an encoded or safely migratable legacy header. */
export function generatedSource(content: string): string | undefined {
  const encoded =
    content.match(ENCODED_HEADER_PATTERN)?.[1] ??
    content.match(FORMER_ENCODED_HEADER_PATTERN)?.[1];
  if (encoded) return decodeSource(encoded);
  const legacy =
    content.match(LEGACY_HEADER_PATTERN)?.[1] ??
    content.match(FORMER_LEGACY_HEADER_PATTERN)?.[1];
  return legacy && !/--|[<>]/.test(legacy) ? legacy : undefined;
}

/** Return whether a document carries the exact expected ownership proof. */
export function hasGeneratedOwnershipHeader(
  content: string,
  sourceRelativePath: string,
): boolean {
  return generatedSource(content) === sourceRelativePath;
}

/** Require every final generated HTML document to retain its source owner. */
export function validateGeneratedOwnershipHeaders(
  outputs: ReadonlyMap<string, string>,
  expectedSources: ReadonlyMap<string, string>,
): void {
  for (const route of outputs.keys()) {
    if (route.endsWith(".html") && !expectedSources.has(route)) {
      throw new MoklyError(
        "build-invalid",
        `${route}: generated HTML has no expected source owner`,
      );
    }
  }
  for (const [route, sourceRelativePath] of expectedSources) {
    const content = outputs.get(route);
    if (
      content === undefined ||
      !hasCurrentGeneratedOwnershipHeader(content, sourceRelativePath)
    ) {
      throw new MoklyError(
        "build-invalid",
        `${route}: generated ownership header is missing or does not match ${sourceRelativePath}`,
      );
    }
  }
}

/** List files proven to be generated by this configured catalogue. */
export function ownedGeneratedRoutes(config: ResolvedConfig): string[] {
  assertSafeGeneratedTree(config);
  return walkFiles(config.mockupsDir)
    .filter((candidate) => isOwned(candidate, config))
    .map((candidate) =>
      toPosixPath(path.relative(config.mockupsDir, candidate)),
    )
    .sort();
}

/** List currently owned routes absent from the next generated output set. */
export function pendingGeneratedOrphanRoutes(
  config: ResolvedConfig,
  expectedRoutes: Iterable<string>,
): string[] {
  const expected = new Set(expectedRoutes);
  return ownedGeneratedRoutes(config).filter((route) => !expected.has(route));
}

/** List generated HTML whose ownership header this configuration cannot claim. */
export function unclaimedGeneratedRoutes(config: ResolvedConfig): string[] {
  assertSafeGeneratedTree(config);
  return walkFiles(config.mockupsDir)
    .flatMap((candidate) => {
      const relative = toPosixPath(path.relative(config.mockupsDir, candidate));
      if (isGeneratedRoute(relative)) return [];
      if (!candidate.endsWith(".html") || relative === MANIFEST_NAME) return [];
      const source = readGeneratedSource(candidate);
      return source &&
        isSafeRepositoryPath(source) &&
        !isAuthoredOwner(source, config)
        ? [relative]
        : [];
    })
    .sort();
}

/** Determine whether an existing target may be replaced safely. */
export function isOwned(candidate: string, config: ResolvedConfig): boolean {
  return generatedOwnershipDenial(candidate, config) === undefined;
}

/** Explain why a target cannot be replaced, retaining the shared source cause. */
export function generatedOwnershipDenial(
  candidate: string,
  config: ResolvedConfig,
): string | undefined {
  try {
    if (!isInside(config.mockupsDir, candidate)) return "is outside mockupsDir";
    const relative = toPosixPath(path.relative(config.mockupsDir, candidate));
    if (isGeneratedRoute(relative)) {
      assertSafeGeneratedPath(candidate, config);
      return fs.lstatSync(candidate).isFile()
        ? undefined
        : "is not a regular file";
    }
    const denial = isAuthoringSource(candidate, config, "all", {
      ignorePublicExclusions:
        candidate === path.join(config.mockupsDir, MANIFEST_NAME),
    });
    if (denial) return sourceDenialMessage(denial);
    if (relative === MANIFEST_NAME) return;
    if (!candidate.endsWith(".html")) return "is not generated HTML";
    if (!fs.lstatSync(candidate).isFile()) return "is not a regular file";
    const source = readGeneratedSource(candidate);
    if (!source || !isSafeRepositoryPath(source))
      return "has no valid generated ownership header";
    if (!isAuthoredOwner(source, config))
      return "has an owner outside every configured entry glob and the source inventory";
  } catch (error) {
    return `could not establish generated ownership: ${errorMessage(error)}`;
  }
}

/**
 * An owner is trusted when it is a resolved entry module, an inventoried input,
 * or a repository-relative path matched by a configured entry glob.
 */
export function isAuthoredOwner(
  sourceRelativePath: string,
  config: ResolvedConfig,
): boolean {
  if (!isSafeRepositoryPath(sourceRelativePath)) return false;
  const absolute = path.resolve(config.repoRoot, sourceRelativePath);
  if (!isInside(config.repoRoot, absolute)) return false;
  return (
    isResolvedEntryOrInventoriedSource(sourceRelativePath, config) ||
    config.entryGlobs.some((glob) =>
      minimatch(sourceRelativePath, glob, { dot: true }),
    )
  );
}

function readGeneratedSource(candidate: string): string | undefined {
  try {
    const handle = fs.openSync(candidate, "r");
    try {
      const buffer = Buffer.alloc(8_192);
      const length = fs.readSync(handle, buffer, 0, buffer.length, 0);
      return generatedSource(buffer.subarray(0, length).toString("utf8"));
    } finally {
      fs.closeSync(handle);
    }
  } catch {
    return undefined;
  }
}

function decodeSource(encoded: string): string | undefined {
  const source = Buffer.from(encoded, "base64").toString("utf8");
  return source.length > 0 &&
    Buffer.from(source, "utf8").toString("base64") === encoded
    ? source
    : undefined;
}

function hasCurrentGeneratedOwnershipHeader(
  content: string,
  sourceRelativePath: string,
): boolean {
  const header = generatedHeader(sourceRelativePath);
  return (
    content.startsWith(header) ||
    content.startsWith(`${header.slice(0, -1)}\r\n`)
  );
}
