/** Plain generated-document notice, never an ownership proof. */
export const GENERATED_MARKER = "<!-- Generated by Mokly. Do not edit. -->\n";

const FORMER_FIRST_LINE =
  /^<!-- Generated by (?:mokly|mokabook)(?:; ownership=v1; source-base64=[A-Za-z0-9+/]+={0,2}| from [^\r\n]+)\. Do not edit\. -->(?:\r\n|\n)/;

/** Ignore historical notices in document comparisons and presentation. */
export function stripGeneratedFirstLine(content: string): string {
  if (content.startsWith(GENERATED_MARKER))
    return content.slice(GENERATED_MARKER.length);
  if (content.startsWith(GENERATED_MARKER.replace("\n", "\r\n")))
    return content.slice(GENERATED_MARKER.length + 1);
  return content.replace(FORMER_FIRST_LINE, "");
}
