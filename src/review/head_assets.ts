import path from "node:path";
import { isDeepStrictEqual } from "node:util";

import { generatedResourceRoute } from "@mokly/viewer/data";
import type { Manifest, HistoricalManifest } from "@mokly/viewer/data";

import { compileCatalogue } from "../build/compile.js";
import { generatedText, type GeneratedFile } from "../build/generated_file.js";
import { projectRealPath } from "../config/paths.js";
import type { ResolvedConfig } from "../config/types.js";
import { MoklyError } from "../errors.js";
import { MANIFEST_NAME } from "../registry/manifest.js";

import {
  AssetInventory,
  assertInventoryPath,
  MissingInventoryAsset,
  inventoryBytes,
} from "./asset_inventory.js";
import { assetError, assertPublicStaticRoute } from "./asset_paths.js";
import {
  FileSystemReviewAssetReader,
  type LocatedReviewAsset,
  type OptionalReviewAssetReader,
  type ReviewAssetReader,
} from "./assets.js";
import { CompilationAssetReader } from "./compilation_assets.js";
import type { DeletionAssetRead } from "./deletion_read.js";

/** Generated bytes come from an accepted compilation; only public resources use disk. */
export class CompiledReviewAssetReader implements OptionalReviewAssetReader {
  private readonly inventory: AssetInventory | undefined;
  private readonly physicalRoot: string;
  private readonly resources: ReviewAssetReader;
  private readonly generated: CompilationAssetReader;
  constructor(
    private readonly headConfig: ResolvedConfig,
    private readonly outputs?: ReadonlyMap<string, GeneratedFile>,
    manifest = outputManifest(outputs),
    resources?: ReviewAssetReader,
  ) {
    this.headConfig = {
      ...headConfig,
      sourceFiles: [
        ...new Set([
          ...(headConfig.sourceFiles ?? []),
          ...(manifest?.sourceFiles ?? []),
        ]),
      ],
    };
    this.resources =
      resources ?? new FileSystemReviewAssetReader(this.headConfig);
    this.generated = new CompilationAssetReader(
      outputs ?? new Map(),
      this.resources,
    );
    this.inventory = manifest
      ? new AssetInventory(this.headConfig, manifest, outputs?.keys())
      : undefined;
    this.physicalRoot = projectRealPath(headConfig.mockupsDir);
  }

  async read(route: string): Promise<Uint8Array> {
    if (generatedResourceRoute(route) === undefined)
      assertPublicStaticRoute(route, this.headConfig);
    const value = await this.readLocated(route);
    if (value.content === undefined)
      throw assetError(
        route,
        generatedResourceRoute(route) === undefined
          ? "file is missing"
          : "not an accepted generated resource",
      );
    return value.content;
  }

  async readIfExists(route: string): Promise<Uint8Array | undefined> {
    return (await this.readLocated(route)).content;
  }

  async readLocated(route: string): Promise<LocatedReviewAsset> {
    assertInventoryPath(route, this.headConfig);
    if (this.inventory && !this.inventory.has(route))
      return { location: this.location(route) };
    const generated = generatedResourceRoute(route);
    if (generated !== undefined) {
      const content = this.outputs?.get(generated);
      if (content === undefined) {
        if (this.inventory) throw new MissingInventoryAsset(route);
        return { location: this.location(route) };
      }
      return {
        content:
          typeof content === "string"
            ? await this.generated.read(route)
            : inventoryBytes(route, content),
        location: this.location(route),
      };
    }
    const value = await this.readAuthored(route);
    if (this.inventory && value.content === undefined)
      throw new MissingInventoryAsset(route);
    return value;
  }

  /** This probe is consumed only by the verified-deletion policy. */
  async readForDeletion(route: string): Promise<DeletionAssetRead> {
    assertInventoryPath(route, this.headConfig);
    if (this.inventory && !this.inventory.has(route)) return { kind: "absent" };
    const authored = generatedResourceRoute(route) === undefined;
    const value = authored
      ? await this.readAuthored(route)
      : await this.readLocated(route);
    return value.content === undefined
      ? authored
        ? { kind: "missing", location: value.location }
        : { kind: "absent" }
      : { kind: "present", bytes: value.content, location: value.location };
  }

  private async readAuthored(route: string): Promise<LocatedReviewAsset> {
    assertPublicStaticRoute(route, this.headConfig);
    if ("readLocated" in this.resources)
      return (this.resources as OptionalReviewAssetReader).readLocated(route);
    const content = this.resources.readIfExists
      ? await this.resources.readIfExists(route)
      : await this.resources.read(route);
    return {
      ...(content === undefined
        ? {}
        : { content: inventoryBytes(route, content) }),
      location: this.location(route),
    };
  }

  private location(route: string): LocatedReviewAsset["location"] {
    return {
      logicalPath: path.resolve(this.headConfig.mockupsDir, route),
      physicalPath: path.resolve(this.physicalRoot, route),
      relativePath: route,
      physicalRelativePath: route,
    };
  }
}

function outputManifest(
  outputs?: ReadonlyMap<string, GeneratedFile>,
): HistoricalManifest | undefined {
  const bytes = outputs?.get(MANIFEST_NAME);
  if (bytes === undefined) return;
  return JSON.parse(generatedText(bytes, MANIFEST_NAME)!) as HistoricalManifest;
}

/** Direct non-HTTP callers may compile once; workers supply their accepted output. */
export async function compiledHeadOutputs(
  config: ResolvedConfig,
  manifest: Manifest,
  outputs?: ReadonlyMap<string, GeneratedFile>,
): Promise<ReadonlyMap<string, GeneratedFile>> {
  if (outputs) return outputs;
  const compilation = await compileCatalogue(config);
  if (!isDeepStrictEqual(compilation.manifest, manifest))
    throw new MoklyError(
      "review-invalid",
      "Catalogue changed before comparison classification",
    );
  return compilation.outputs;
}
