//! Independently runnable file and generated-artifact policies.

use clap::Subcommand;

/// Checks that need repository files or generated stdout.
#[derive(Clone, Copy, Debug, Subcommand)]
pub(crate) enum PolicyCommand {
    /// Reject MIT dependencies on cloud crates, packages, or imports.
    Boundary,
    /// Reject trailing spaces and missing final newlines in Git-visible text.
    Whitespace,
    /// Validate the append-only cloud migration lock.
    MigrationImmutability,
    /// Check protocol, manifest, image, and installed toolchain pins.
    ToolchainPins,
    /// Generate the Rust-owned OpenAPI document and its TypeScript client.
    Openapi {
        /// Compare the generated bytes without writing them.
        #[arg(long)]
        check: bool,
    },
    /// Validate API error reasons and GitHub delivery fixtures.
    OpenapiLint,
}
