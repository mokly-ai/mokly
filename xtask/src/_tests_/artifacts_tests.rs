#[test]
fn native_inventory_uses_the_package_inventory_schema() {
    let digest = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
    assert_eq!(
        native_inventory("mokly", digest.into()).unwrap(),
        concat!(
            "{\n  \"schemaVersion\": 1,\n  \"files\": [\n    {\n",
            "      \"path\": \"mokly\",\n",
            "      \"sha256\": \"ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad\"\n",
            "    }\n  ]\n}\n"
        )
    );
}

#[test]
fn maps_exactly_the_five_supported_targets() {
    for (os, architecture, package, executable) in [
        ("linux", "x86_64", "linux-x64-gnu", "mokly"),
        ("linux", "aarch64", "linux-arm64-gnu", "mokly"),
        ("macos", "x86_64", "darwin-x64", "mokly"),
        ("macos", "aarch64", "darwin-arm64", "mokly"),
        ("windows", "x86_64", "win32-x64-msvc", "mokly.exe"),
    ] {
        let host = Host::resolve(os, architecture).unwrap();
        assert_eq!(host.package, package);
        assert_eq!(host.executable, executable);
    }
    assert!(Host::resolve("windows", "aarch64").is_err());
    assert!(Host::resolve("linux", "riscv64").is_err());
}

#[test]
fn build_runs_cargo_before_copying_to_the_host_package() {
    let mock = Arc::new(Unimock::new((
        CommandRunnerRunMock.next_call(matching!((spec) if spec.display().starts_with("cargo build --locked ") && spec.display().contains("--target x86_64-unknown-linux-gnu") && spec.display().contains("--bin mokly") && spec.working_directory() == Some(Path::new("/workspace")))).returns(Ok(())),
        RemoveMock.next_call(matching!((path) if *path == Path::new("/workspace/packages/native-linux-x64-gnu/bin/.runtime-inventory.json"))).returns(Ok(())),
        CopyMock.next_call(matching!((source, destination) if *source == Path::new("/workspace/target/native/x86_64-unknown-linux-gnu/debug/mokly") && *destination == Path::new("/workspace/packages/native-linux-x64-gnu/bin/mokly"))).returns(Ok(())),
        DigestMock.next_call(matching!((path) if *path == Path::new("/workspace/packages/native-linux-x64-gnu/bin/mokly"))).returns(Ok("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad".into())),
        WriteMock.next_call(matching!((path, text) if *path == Path::new("/workspace/packages/native-linux-x64-gnu/bin/.runtime-inventory.json") && *text == native_inventory("mokly", "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad".into()).unwrap())).returns(Ok(())),
    )));
    let tasks: &dyn Artifacts = &DefaultArtifacts {
        workspace: "/workspace".into(),
        os: "linux".into(),
        architecture: "x86_64".into(),
        commands: mock.clone(),
        files: mock,
    };
    tasks.build_native().unwrap();
}

#[test]
fn generated_source_goes_to_the_model_package_import_path() {
    let mock = Arc::new(Unimock::new((
        WriteMock.some_call(matching!((path, text) if *path == Path::new("/workspace/packages/model/src/generated/model.ts") && *text == typescript::generate())).returns(Ok(())),
        WriteMock.each_call(matching!((path, text) if path.starts_with("/workspace/packages/model/src/generated/catalogue") && text.contains("// Generated by cargo xtask generate-types."))).answers(&|_, _, _| Ok(())),
        WriteMock.each_call(matching!((path, text) if path.starts_with("/workspace/packages/mokly/src/generated/sidecar") && text.contains("// Generated by cargo xtask generate-types."))).answers(&|_, _, _| Ok(())),
    )));
    let tasks: &dyn Artifacts = &DefaultArtifacts {
        workspace: "/workspace".into(),
        os: "linux".into(),
        architecture: "x86_64".into(),
        commands: mock.clone(),
        files: mock,
    };
    tasks.generate_types().unwrap();
}

#[test]
fn generation_works_without_a_native_host_package() {
    let mock = Arc::new(Unimock::new(
        WriteMock
            .each_call(matching!(_, _))
            .answers(&|_, _, _| Ok(())),
    ));
    let tasks: &dyn Artifacts = &DefaultArtifacts {
        workspace: "/workspace".into(),
        os: "linux".into(),
        architecture: "riscv64".into(),
        commands: mock.clone(),
        files: mock,
    };
    tasks.generate_types().unwrap();
    assert!(matches!(
        tasks.build_native(),
        Err(Error::NativeHost { .. })
    ));
}
